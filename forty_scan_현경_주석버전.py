# 4. Multi-hot 벡터화 (이 프로그램의 핵심 로직)
# ==========================================================
# [핵심 개념] Multi-hot encoding이란?
#
# "One-hot encoding"은 여러 개 중 정답 1개만 1로 표시하는 방식이고,
# "Multi-hot encoding"은 여러 개가 동시에 해당할 수 있고,
# 이 프로젝트에서는 한 걸음 더 나아가 "몇 번 나왔는지 횟수"까지
# 그대로 숫자로 담습니다.
#
# 예시:
#   문장: "라떼는 말이야 우리 때는!! 나 때는 진짜 힘들었어"
#
#   특징 "라떼_나때" 패턴(라떼|나 때|우리 때)이 이 문장에서
#   "라떼", "우리 때", "나 때" 이렇게 3번 매칭됨 → 값 3
#
#   특징 "느낌표" 패턴(!)이 "!!"에서 2번 매칭됨 → 값 2
#
#   나머지 특징들은 매칭이 없으므로 → 값 0
#
#   결과 벡터(28개 숫자로 구성): [0, 0, ..., 3(라떼_나때 자리), ..., 2(느낌표 자리), ..., 0]
# ==========================================================


def text_to_multihot(text, patterns=COMPILED_PATTERNS):
    """
    문장 1개를 28차원 multi-hot 벡터로 변환합니다.

    특징이 등장한 '횟수'를 그대로 값으로 사용합니다.

    예:

    "라떼는 말이야 우리 때는!! 나 때는 진짜 힘들었어"

    라떼_나때 → 3 (라떼, 우리 때, 나 때)
    느낌표    → 2
    나머지    → 0
    """

    # 만약 text가 None(값이 아예 없음)으로 들어오면 빈 문자열로 처리합니다.
    # (CSV에서 특정 행의 값이 비어있는 경우를 대비한 방어 코드)
    if text is None:
        text = ""

    # text가 숫자 등 다른 타입으로 들어와도 안전하게 문자열로 강제 변환합니다.
    text = str(text)

    vector = []  # 이 문장의 28개 특징 값을 순서대로 담을 빈 리스트

    # 컴파일해둔 정규식 패턴 28개를 순서대로 하나씩 꺼내서
    for pattern in patterns:
        # pattern.findall(text) → 이 문장 안에서 패턴과 일치하는 부분을
        #                          모두 찾아서 리스트로 반환 (예: ["ㅎㅎ", "ㅎㅎㅎ"])
        # len(...) → 그 리스트의 길이 = 몇 번 매칭되었는지(등장 횟수)
        count = len(pattern.findall(text))
        vector.append(count)

    # 파이썬 리스트를 numpy 배열로 바꿔서 반환합니다.
    # (numpy 배열이어야 이후 모델(sklearn)에 바로 넣을 수 있습니다)
    return np.array(vector, dtype=float)


def transform_texts(texts):
    """여러 문장을 (샘플 수, 28) 크기의 multi-hot 행렬로 변환합니다.

    예를 들어 문장이 2000개, 특징이 28개면
    결과는 2000행 x 28열짜리 숫자 표(행렬)가 됩니다.
    한 행 = 문장 하나의 벡터.
    """

    # 문장을 하나씩 꺼내서 text_to_multihot으로 벡터로 바꾸고,
    # 그 벡터들을 다시 하나의 큰 numpy 배열(행렬)로 묶습니다.
    return np.array([text_to_multihot(text) for text in texts])


