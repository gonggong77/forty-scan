# 12. 새 문장 판독 함수
# ==========================================================
# 지금까지는 "이미 정답을 아는 데이터"로 모델을 학습/평가했다면,
# 여기서부터는 "정답을 모르는 새 문장"이 들어왔을 때 실제로
# 영포티 점수를 계산해주는 함수를 만듭니다.


def predict_forty(text):
    """
    문장 1개를 판독합니다.

    반환값:
    score        : 영포티 지수 (0~100)
    vector       : 28차원 multi-hot 벡터
    contributions: (특징명, 등장횟수, 계수, 기여도) 리스트 (기여도 절댓값 내림차순)
    """

    # 1) 입력 문장을 학습 때와 똑같은 방식으로 28차원 벡터로 변환
    vector = text_to_multihot(text)

    # 2) 학습된 모델에 벡터를 넣어서 "영포티(클래스 1)일 확률"을 구함
    #    predict_proba → [[일반일 확률, 영포티일 확률]] 형태의 2차원 배열을 반환하므로
    #    [0][1]로 "첫 번째(유일한) 샘플의, 영포티(index 1)일 확률"만 꺼냄
    #    reshape(1, -1) → 벡터 하나를 "샘플 1개짜리 표"모양((1, 28))으로 바꿔주는 것
    #                      (sklearn은 항상 "여러 개의 샘플이 들어있는 표" 형태를 기대하기 때문)
    #    * 100 → 0~1 사이 확률을 0~100 점수로 변환
    score = model.predict_proba(vector.reshape(1, -1))[0][1] * 100

    contributions = []  # "이 문장에서 실제로 검출된 특징들"만 모아둘 리스트

    # 28개 특징 이름, 이 문장에서의 등장 횟수, 각 특징의 학습된 가중치를
    # 한 번에 짝지어(zip) 순서대로 확인합니다.
    for name, count, coef in zip(FEATURE_NAMES, vector, coefficients):
        if count > 0:  # 실제로 이 문장에서 등장한 특징만 결과에 포함 (0회는 스킵)
            # 기여도 = 등장 횟수 × 가중치
            # → "몇 번 나왔는지"와 "얼마나 중요한 특징인지"를 곱해서
            #    이 특징이 최종 점수에 실제로 얼마나 영향을 줬는지를 나타냄
            contributions.append((name, int(count), coef, count * coef))

    # 기여도의 절댓값이 큰 순서(=영향력이 큰 순서)로 정렬
    # (기여도가 음수든 양수든, "영향을 많이 준" 순서로 보여주기 위함)
    contributions.sort(key=lambda item: abs(item[3]), reverse=True)

    return score, vector, contributions


