# [핵심 개념] 왜 데이터를 나누는가?
#
# 모델을 "학습에 쓴 문제로 다시 시험 보게" 하면 answer를 외워서
# 맞추는 것처럼 실제 실력보다 점수가 부풀려집니다(과적합, overfitting).
# 그래서 데이터를 미리 두 그룹으로 나눠서
#   - 학습용(train): 모델이 패턴을 배우는 데 사용
#   - 검증용(test) : 모델이 "한 번도 안 본 문제"로 실력을 테스트하는 데 사용
# 이렇게 나눠서 채점해야 실제 성능을 신뢰할 수 있습니다.

print()
