# ==========================================================
# 3. 등급 기준표
# ==========================================================
# 모델이 계산한 "영포티 지수(0~100점)"를 사람이 이해하기 쉬운
# 5단계 등급(이름 + 코멘트)으로 바꿔주는 표입니다.
#
# 구조: (이 점수 미만이면, 등급 이름, 설명 코멘트)
# 예) score = 55 라면
#     20보다 큼 → 40보다 큼 → 60보다 작음 → "영포티 경계" 등급 확정
# ==========================================================

GRADES = [
    (20, "진성 MZ", "영포티 특징이 거의 없습니다."),
    (40, "정상 범주", "무난한 말투입니다."),
    (60, "영포티 경계", "슬슬 물결(~)과 마침표를 조심하세요."),
    (80, "MZ 코스프레 40대", "젊은 척이 살짝 티납니다."),
    (101, "확진 영포티", "라떼 향이 진하게 감지되었습니다."),
    # 101로 잡아둔 이유: score는 최대 100점이라 "100 미만"으로 하면
    # 정확히 100점일 때 아무 구간에도 안 걸리는 버그가 생깁니다.
    # 101로 여유를 둬서 100점도 확실히 마지막 등급에 걸리게 만든 것입니다.
]


def get_grade(score):
    """영포티 지수(0~100)를 5단계 등급으로 변환합니다.

    동작 방식: GRADES를 위에서부터 순서대로 보면서
    "score가 이 기준(upper)보다 작다"를 처음 만족하는 곳에서 멈추고
    그 등급을 반환합니다. (마치 계단을 하나씩 확인하는 것과 같음)
    """

    for upper, name, comment in GRADES:
        if score < upper:
            return name, comment

    # 이론적으로는 위 for문 안에서 항상 return 되지만(101이 마지막 기준이라
    # 100점 이하의 모든 값을 커버함), 혹시 모를 예외 상황을 대비해
    # 안전장치로 마지막 등급을 반환합니다.
    return GRADES[-1][1], GRADES[-1][2]


