# 13. 대화형 판독 루프 (사용자가 실제로 사용하는 부분)
# ==========================================================
# 여기서부터는 콘솔에서 사용자가 문장을 직접 입력하면
# 바로바로 점수를 계산해서 보여주는 "무한 반복 루프"입니다.
# q, exit, quit 중 하나를 입력하거나 Ctrl+C를 누르면 종료됩니다.

print()
print("=" * 70)
print(" [영포티 판독기]  분석할 문장을 입력하세요.")
print(" 종료하려면 q 또는 exit 를 입력하세요.")
print("=" * 70)

while True:  # 사용자가 종료하지 않는 한 계속 반복

    try:
        # 콘솔에서 한 줄 입력을 받고, 앞뒤 공백은 제거
        user_input = input("\n판독할 문장 > ").strip()
    except (EOFError, KeyboardInterrupt):
        # EOFError: 입력 스트림이 예기치 않게 끝난 경우 (예: 파이프로 실행 중 입력 종료)
        # KeyboardInterrupt: 사용자가 Ctrl+C를 누른 경우
        # 둘 다 "더 이상 입력을 받을 수 없다"는 뜻이므로 루프를 정상 종료
        print("\n판독기를 종료합니다.")
        break

    if user_input.lower() in ("q", "exit", "quit"):
        # 대소문자 구분 없이 q/exit/quit 중 하나면 종료
        print("판독기를 종료합니다.")
        break

    if not user_input:
        # 아무것도 입력하지 않고 엔터만 쳤다면, 다시 입력받기(무시하고 계속)
        continue

    # 실제 판독 실행
    score, vector, contributions = predict_forty(user_input)
    grade, comment = get_grade(score)

    print()
    print("-" * 70)
    print(f" 영포티 지수 : {score:.1f}%   [{grade}]")
    print(f" {comment}")
    print("-" * 70)

    if contributions:
        # 검출된 특징이 1개 이상 있으면, 표 형태로 상세 내역을 출력
        print(f" {'검출된 특징':<18}{'횟수':>6}{'가중치':>10}{'기여도':>10}")
        print(" " + "-" * 68)

        for name, count, coef, contribution in contributions:
            print(f" {name:<18}{count:>6}{coef:>+10.2f}{contribution:>+10.2f}")
    else:
        # 검출된 특징이 하나도 없으면 안내 문구만 출력
        print(" 사전에 등록된 특징이 검출되지 않았습니다.")

    print(" " + "-" * 68)
    print(f" multi-hot 벡터 : {vector.astype(int).tolist()}")
    print("-" * 70)
